import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { Suspense } from "react";
import { NextNavAdapter } from "./adapter";
import { ContentInstallerHost } from "./installer";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
  // The web app manifest (public/manifest.webmanifest) makes the app installable for the content installer.
  manifest: "/manifest.webmanifest",
};

export const viewport: Viewport = {
  themeColor: "#000000",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/* The content installer (off unless NEXT_PUBLIC_CONTENT_INSTALLER=on) wraps every route; its toast and
            installed-app offer sit beside the navigation adapter. */}
        <ContentInstallerHost>
          <Suspense fallback={null}>
            <NextNavAdapter>{children}</NextNavAdapter>
          </Suspense>
        </ContentInstallerHost>
      </body>
    </html>
  );
}
